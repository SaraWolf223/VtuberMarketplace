/**
 * Bundles docs/legal/*.md into src/content/legal-content.generated.ts for in-app viewing.
 * Run: node scripts/generate-legal-content.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { applyLegalIdentity, readLegalIdentity } from './legal-template-values.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const docsDir = path.join(root, 'docs', 'legal');
const outFile = path.join(root, 'src', 'content', 'legal-content.generated.ts');
const identity = readLegalIdentity(docsDir);

const FILES = {
  terms: 'TERMS_OF_SERVICE.md',
  privacy: 'PRIVACY_POLICY.md',
  community: 'COMMUNITY_GUIDELINES.md',
  sellerAgreement: 'SELLER_AGREEMENT.md',
  buyerPurchaseTerms: 'BUYER_PURCHASE_TERMS.md',
  dmcaCopyrightPolicy: 'DMCA_COPYRIGHT_POLICY.md',
};

function escapeTemplateLiteral(value) {
  return value.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
}

const entries = Object.entries(FILES).map(([id, filename]) => {
  const filePath = path.join(docsDir, filename);
  const content = applyLegalIdentity(fs.readFileSync(filePath, 'utf8'), identity);
  return `  ${id}: \`${escapeTemplateLiteral(content)}\`,`;
});

const output = `/** Auto-generated by scripts/generate-legal-content.mjs — do not edit by hand. */
import type { LegalDocumentId } from '@/constants/legal';

export const LEGAL_MARKDOWN: Record<LegalDocumentId, string> = {
${entries.join('\n')}
};
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, output, 'utf8');
console.log(`Wrote ${outFile}`);
