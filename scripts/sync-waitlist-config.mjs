/**
 * Writes website/scripts/waitlist-config.js from root .env (EXPO_PUBLIC_SUPABASE_*).
 * Usage: node scripts/sync-waitlist-config.mjs
 */
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const envPath = path.join(root, '.env');
const outPath = path.join(root, 'website', 'scripts', 'waitlist-config.js');

function parseEnv(text) {
  const out = {};
  for (const line of text.split('\n')) {
    const t = line.trim();
    if (!t || t.startsWith('#')) continue;
    const i = t.indexOf('=');
    if (i < 0) continue;
    const key = t.slice(0, i).trim();
    let val = t.slice(i + 1).trim();
    if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
      val = val.slice(1, -1);
    }
    out[key] = val;
  }
  return out;
}

let env = {};
if (fs.existsSync(envPath)) {
  env = parseEnv(fs.readFileSync(envPath, 'utf8'));
}

const url = env.EXPO_PUBLIC_SUPABASE_URL || '';
const key = env.EXPO_PUBLIC_SUPABASE_ANON_KEY || '';
const turnstileSiteKey = env.EXPO_PUBLIC_TURNSTILE_SITE_KEY || '';

const contents = `/** Auto-generated by scripts/sync-waitlist-config.mjs — do not commit secrets in public repos */
window.LOCAL_MARKETPLACE_WAITLIST = {
  supabaseUrl: ${JSON.stringify(url)},
  supabaseAnonKey: ${JSON.stringify(key)},
  source: 'landing-page',
  formspreeEndpoint: '',
  turnstileSiteKey: ${JSON.stringify(turnstileSiteKey)},
};
`;

fs.writeFileSync(outPath, contents);
console.log('Wrote', outPath, url ? '(Supabase URL set)' : '(missing EXPO_PUBLIC_SUPABASE_URL in .env)');
